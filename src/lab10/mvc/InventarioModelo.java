package lab10.mvc;

import java.math.BigDecimal;
import java.sql.*;
import java.util.ArrayList;
import java.util.List;

public class InventarioModelo {
    private final String url;

    public record Registro(int id, String nombre, BigDecimal precio, int stock, String categoria) { }

    public InventarioModelo(String url) throws SQLException {
        this.url = url;
        try {
            Class.forName("org.hsqldb.jdbcDriver");
        } catch(ClassNotFoundException e) {
            throw new SQLException("Agrega la dependencia JDBC HSQLDB al proyecto.",e);
        }
        try(Connection con = conectar()) {
            DatabaseMetaData meta = con.getMetaData();
            try(ResultSet rs = meta.getTables(null, null, "PRODUCTOS", null)) {
                if(!rs.next()) {
                    try(Statement s=con.createStatement()) {
                        s.execute("CREATE TABLE productos (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(100) NOT NULL, precio DECIMAL(12,2) NOT NULL, stock INTEGER NOT NULL, categoria VARCHAR(80) NOT NULL)");
                    }
                }
            }
        }
    }

    private Connection conectar() throws SQLException { return DriverManager.getConnection(url,"sa",""); }

    public List<Registro> listar() throws SQLException {
        List<Registro> lista = new ArrayList<>();
        try(Connection con=conectar(); PreparedStatement ps=con.prepareStatement("SELECT id,nombre,precio,stock,categoria FROM productos ORDER BY id");ResultSet rs=ps.executeQuery()) {
            while(rs.next()) lista.add(new Registro(rs.getInt(1),rs.getString(2),rs.getBigDecimal(3),rs.getInt(4),rs.getString(5)));
        }
        return lista;
    }

    public void guardar(Integer id,String nombre,BigDecimal precio,int stock,String categoria) throws SQLException {
        if(nombre == null || nombre.isBlank() || categoria == null || categoria.isBlank() || precio.signum()<0 || stock<0) {
            throw new IllegalArgumentException("Datos del producto invalidos.");
        }
        String sql = id == null ? "INSERT INTO productos (nombre,precio,stock,categoria) VALUES (?,?,?,?)" : "UPDATE productos SET nombre=?,precio=?,stock=?,categoria=? WHERE id=?";
        try(Connection con=conectar();PreparedStatement ps=con.prepareStatement(sql)) {
            ps.setString(1,nombre.trim());ps.setBigDecimal(2,precio);ps.setInt(3,stock);ps.setString(4,categoria.trim());
            if(id!=null)ps.setInt(5,id);
            ps.executeUpdate();
        }
    }

    public void eliminar(int id) throws SQLException {
        try(Connection con=conectar();PreparedStatement ps=con.prepareStatement("DELETE FROM productos WHERE id=?")) {
            ps.setInt(1,id);ps.executeUpdate();
        }
    }

    public void cerrar() throws SQLException {
        try(Connection con=conectar();Statement stmt=con.createStatement()) {
            stmt.execute("SHUTDOWN");
        }
    }
}
